export const CITIES: City[] = RAW.map(([name, state, lat, lon]) => ({ name, state, lat, lon }));

const simplify = (s: string) => s.toLowerCase().normalize('NFKD').replace(/[^a-z0-9 ]/g, '');

/** Case-insensitive search by city or state; names that start with the query come first. */
export function searchCities(query: string, limit = 8): City[] {
  const q = simplify(query.trim());
  if (!q) return [];
  const starts: City[] = [];
  const contains: City[] = [];
  for (const c of CITIES) {
    const n = simplify(c.name);
    if (n.startsWith(q) || n.split(' ').some((w) => w.startsWith(q))) starts.push(c);
    else if (n.includes(q) || simplify(c.state).startsWith(q)) contains.push(c);
  }
  return [...starts, ...contains].slice(0, limit);
}

export const cityLabel = (c: City) => `${c.name}, ${c.state}`;
